#!/usr/bin/env python3
"""Generate an example with N distinct row components for bough-x (journal P14: compile time and size).

  gen_components.py N distinct|shared OUT.rs

distinct: every component has its own three functions, so every archetype in the program is distinct (each gets
its own delta, paint and replace kernels). shared: components differ in shape only and reuse four functions.
"""
import sys
n, mode, out = int(sys.argv[1]), sys.argv[2], sys.argv[3]
o = []
o.append("// generated by bench/r8/gen_components.py; do not edit\n#![allow(dead_code)]\nuse bough_x::prelude::*;\nuse bough_x::soft::Soft;\n")
o.append("lens!(Theme: u32 = 0);\nlens!(Hot: u32 = 1);\nlens!(Scroll: i32 = 2);\n")
o.append("struct App { u: U, data: Vec<Rel<[i32; 4]>> }\n")
if mode == "shared":
    o.append("fn bg((t, h, k): (u32, u32, u32)) -> Color { Color(if h == k { 0xff3366 } else if t != 0 { 0x101010 } else { 0xf0f0f0 }) }\n")
    o.append("fn fg(t: u32) -> Color { Color(if t != 0 { 0xeeeeee } else { 0x111111 }) }\n")
    o.append("fn bar((t, k): (u32, u32)) -> Color { Color((k.wrapping_mul(2654435761) >> 8) ^ (t * 0x808080)) }\n")
for c in range(n):
    if mode == "distinct":
        o.append(f"fn bg{c}((t, h, k): (u32, u32, u32)) -> Color {{ Color(if h == k {{ 0xff3366 + {c} }} else if t != 0 {{ 0x101010 + {c} }} else {{ 0xf0f0f0 - {c} }}) }}\n")
        o.append(f"fn fg{c}(t: u32) -> Color {{ Color(if t != 0 {{ 0xeeeeee - {c} }} else {{ 0x111111 + {c} }}) }}\n")
        o.append(f"fn bar{c}((t, k): (u32, u32)) -> Color {{ Color((k.wrapping_mul(2654435761 + {c}) >> 8) ^ (t * 0x808080)) }}\n")
        bg, fg, bar = f"bg{c}", f"fg{c}", f"bar{c}"
    else:
        bg, fg, bar = "bg", "fg", "bar"
    # shapes vary with c so that components are distinct types even when functions are shared
    cells = 2 + c % 5
    leaves = 2 + 2 * cells + (1 if c % 2 else 0)
    o.append(f"const SHAPE{c}: [Rect; {leaves}] = {{ let mut r = [Rect::new(0, 0, 60, 30); {leaves}]; let mut i = 0; while i < {leaves} {{ r[i] = Rect::new(60 * (i as i32 / 2), 0, 60, 30); i += 1; }} r }};\n")
    extra = f", Fill((un::<Theme>(), rec(r as u32 + {c})).map({bar}))" if c % 2 else ""
    o.append(f"""#[inline(never)]
fn part{c}<S: Sink<App>>(app: &App, s: &mut S) {{
    let theme = un::<Theme>();
    s.scope(Space {{ clip: Rect::new(0, {c} * 8, 2560, 400), base: (0, {c} * 8), scroll: Scroll::SLOT as u8 }}, |s| {{
        let rel = &app.data[{c}];
        s.list(&List {{ n: rel.len() as u32, row_h: 30, x: 0, y: 0, shape: &SHAPE{c}, edits: &rel.journal }}, |r| {{
            let v = rel.get(r);
            (
                Fill(theme.map({fg})),
                Num::<0, _, _>(rec(r as i32), theme.map({fg})),
                std::array::from_fn::<_, {cells}, _>(|k| (Fill((theme, un::<Hot>(), rec(k as u32)).map({bg})), Num::<{c % 3}, _, _>(rec(v[k % 4]), theme.map({fg})))){extra}
            )
        }});
    }});
}}
""")
o.append("impl View for App {\n    fn block(&self) -> &U { &self.u }\n    fn view<S: Sink<Self>>(&self, s: &mut S) {\n")
for c in range(n):
    o.append(f"        part{c}(self, s);\n")
o.append("    }\n}\n")
o.append(f"""fn main() {{
    let mut app = App {{ u: U::default(), data: (0..{n}).map(|c| Rel::new((0..1000).map(|r| [r as i32, c as i32, 7, 9]).collect())).collect() }};
    let mut world = World::<Soft>::new(2560, 1600, 3);
    world.mount(&app);
    let mut soft = Soft::new(2560, 1600);
    world.paint(&mut soft);
    world.tiles.clear();
    app.u.set::<Theme>(1);
    app.u.set::<Hot>(2);
    world.settle(&app);
    let t = world.tiles.count();
    app.data[0].edit(3)[0] = 99;
    app.u.set::<Scroll>(90);
    world.settle(&app);
    world.redescribe(&app);
    soft.repair(&world.tiles, |s| world.paint(s));
    let sum = soft.px.iter().fold(0u64, |a, &p| a.wrapping_mul(31).wrapping_add(p as u64));
    println!("components={n} tiles={{t}} records={{}} checksum={{sum:x}}", world.root.stats().0);
}}
""")
open(out, "w").write("".join(o))
